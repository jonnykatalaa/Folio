export const sectorSummaries: SectorSummary[] = Object.values(
  assets.reduce<Record<string, SectorSummary>>((accumulator, asset) => {
    const current = accumulator[asset.sector] ?? {
      name: asset.sector,
      marketCap: 0,
      change24h: 0,
      assetCount: 0,
    };
    current.marketCap += asset.marketCap;
    current.change24h += asset.change24h;
    current.assetCount += 1;
    accumulator[asset.sector] = current;
    return accumulator;
  }, {}),
)
  .map((sector) => ({
    ...sector,
    change24h: sector.change24h / sector.assetCount,
  }))
  .sort((first, second) => second.marketCap - first.marketCap);

