function generateSparkline(base: number, volatility: number, trend: number): number[] {
  const points: number[] = [];
  let current = base * (1 - volatility * 3);
  for (let i = 0; i < 24; i++) {
    const change = (Math.random() - 0.45 + trend * 0.01) * volatility * base;
    current = Math.max(current + change, base * 0.5);
    points.push(Math.round(current * 100) / 100);
  }
  return points;
}

